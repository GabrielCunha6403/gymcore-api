        alter table tipo_aplicacao_desconto add constraint uk_tipo_aplicacao_desconto_codigo unique (codigo);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'uk_condicao_desconto_codigo') then
        alter table condicao_desconto add constraint uk_condicao_desconto_codigo unique (codigo);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'uk_forma_pagamento_codigo') then
        alter table forma_pagamento add constraint uk_forma_pagamento_codigo unique (codigo);
    end if;

    if not exists (select 1 from pg_constraint where conname = 'uk_role_estabelecimento_codigo') then
        alter table role_estabelecimento add constraint uk_role_estabelecimento_codigo unique (codigo);
    end if;
end $$;


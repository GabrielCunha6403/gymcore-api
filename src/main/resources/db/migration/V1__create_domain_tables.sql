create table if not exists tipo_estabelecimento (
    id_tipo_estabelecimento bigint generated by default as identity primary key,
    codigo varchar(40) not null,
    descricao varchar(100),
    ativo boolean not null default true
);

create table if not exists tipo_cobranca (
    id_tipo_cobranca bigint generated by default as identity primary key,
    codigo varchar(30) not null,
    descricao varchar(100),
    ativo boolean not null default true
);

create table if not exists tipo_desconto (
    id_tipo_desconto bigint generated by default as identity primary key,
    codigo varchar(30) not null,
    descricao varchar(100),
    ativo boolean not null default true
);

create table if not exists tipo_aplicacao_desconto (
    id_tipo_aplicacao_desconto bigint generated by default as identity primary key,
    codigo varchar(30) not null,
    descricao varchar(150),
    ativo boolean not null default true
);

create table if not exists condicao_desconto (
    id_condicao_desconto bigint generated by default as identity primary key,
    codigo varchar(50) not null,
    descricao varchar(150),
    ativo boolean not null default true
);

create table if not exists forma_pagamento (
    id_forma_pagamento bigint generated by default as identity primary key,
    codigo varchar(40) not null,
    descricao varchar(100),
    permite_recorrencia boolean not null default false,
    ativo boolean not null default true
);

create table if not exists role_estabelecimento (
    id_role_estabelecimento bigint generated by default as identity primary key,
    codigo varchar(40) not null,
    descricao varchar(100),
    ativo boolean not null default true
);

do $$
begin
